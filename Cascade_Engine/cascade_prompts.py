def build_city_rollup_prompt(
    active_alerts      : list[dict[str, Any]],
    sequence_number    : int = 1,
) -> str:
    """
    Builds the user-turn prompt for city-level cascade rollup.

    Parameters
    ----------
    active_alerts    : list of SectorRecord.to_dict() for all alerting sectors
    sequence_number  : incident sequence number for incident_id generation

    Returns
    -------
    str — formatted user prompt ready for chat completion
    """
    from datetime import datetime, timezone
    now      = datetime.now(timezone.utc)
    date_str = now.strftime("%Y_%m%d")
    seq_str  = str(sequence_number).zfill(3)

    alert_blocks = "\n\n".join([
        f"SECTOR {i+1}: {a.get('sectorId')} ({a.get('district')})\n"
        f"  Domain      : {a.get('domain')}\n"
        f"  Health Score: {a.get('healthScore')}\n"
        f"  Anomaly     : {a.get('anomalyLevel', '').upper()}\n"
        f"  Metric      : {a.get('metricValue')}\n"
        f"  Signal      : {a.get('signal')}\n"
        f"  Location    : {a.get('location', {}).get('placeName', 'Unknown')}\n"
        f"  Alerting For: {a.get('alertSince', 'unknown')}"
        for i, a in enumerate(active_alerts)
    ])

    return f"""\
CITYWIDE CASCADE INCIDENT REPORT
==================================
Timestamp        : {now.isoformat()}
Suggested ID     : CITY_INCIDENT_{date_str}_{seq_str}
Active Sectors   : {len(active_alerts)}
Sector IDs       : {[a.get('sectorId') for a in active_alerts]}

ACTIVE SECTOR ALERTS:
{alert_blocks}

Synthesize the above into a CityCascadeRollup JSON assessment for \
the Delhi Emergency Operations Centre.
"""