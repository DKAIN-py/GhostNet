"""
AutoNet — Cascade Prompts & Pydantic Schema Definitions
========================================================
Defines the two structured output contracts for Qwen2.5-Coder-7B-Instruct:
  1. SectorCascadeAlert  — per-sector crisis diagnosis
  2. CityCascadeRollup   — city-wide multi-sector aggregation

All schemas use Pydantic v2 syntax. `model_json_schema()` output is passed
directly into llama-server's `response_format` field for GBNF grammar
enforcement — guaranteeing zero-hallucination, 100% valid JSON output.

Author  : AutoNet Systems Team
Runtime : Python 3.11+ | Pydantic v2
"""

from __future__ import annotations

from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


# ─────────────────────────────────────────────────────────────────────────────
# SECTION 1 — ENUMS
# ─────────────────────────────────────────────────────────────────────────────

class SectorSeverity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH     = "HIGH"
    MEDIUM   = "MEDIUM"


class CityThreatLevel(str, Enum):
    RED    = "RED"
    ORANGE = "ORANGE"
    YELLOW = "YELLOW"


# ─────────────────────────────────────────────────────────────────────────────
# SECTION 2 — PYDANTIC OUTPUT MODELS
# ─────────────────────────────────────────────────────────────────────────────

class SectorCascadeAlert(BaseModel):
    """
    Structured LLM output for a single-sector cascade diagnosis.

    Generated by Qwen2.5 when a sector's healthScore drops below 35.
    Passed to the frontend via Socket.io `cascade-alert` event.
    """

    sector_id: str = Field(
        ...,
        description="The sectorId string for the affected sector (e.g. 'DEL_EAST_LN').",
    )
    severity: SectorSeverity = Field(
        ...,
        description="Assessed threat severity for this sector.",
    )
    root_causes: list[str] = Field(
        ...,
        min_length=1,
        max_length=5,
        description="Concise list of identified root causes driving the anomaly.",
    )
    cascade_risk: str = Field(
        ...,
        description=(
            "Single sentence describing the downstream cascade risk if "
            "this sector is not mitigated — which adjacent sectors or "
            "domains are most vulnerable."
        ),
    )
    mitigation_actions: list[str] = Field(
        ...,
        min_length=1,
        max_length=5,
        description=(
            "Ordered list of concrete, agency-specific mitigation actions. "
            "Each must name a responsible agency (e.g. PWD, DTC, DISCOM)."
        ),
    )
    confidence_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description=(
            "Model's confidence in this diagnosis (0.0–1.0), "
            "based on signal clarity and historical pattern match."
        ),
    )


class CityCascadeRollup(BaseModel):
    """
    Structured LLM output for a city-wide multi-sector cascade aggregation.

    Generated by Qwen2.5 when ≥ 3 sectors are simultaneously alerting.
    Passed to the frontend via Socket.io `city-cascade` event.
    """

    incident_id: str = Field(
        ...,
        description=(
            "Unique incident identifier. Format: CITY_INCIDENT_YYYY_MMDD_NNN "
            "where NNN is a zero-padded sequence number."
        ),
    )
    affected_sectors: list[str] = Field(
        ...,
        description="List of sectorId strings contributing to this citywide cascade.",
    )
    city_threat_level: CityThreatLevel = Field(
        ...,
        description=(
            "Composite city-wide threat level. RED = immediate multi-district emergency, "
            "ORANGE = spreading cascade requiring coordinated response, "
            "YELLOW = elevated multi-sector watch."
        ),
    )
    executive_summary: str = Field(
        ...,
        description=(
            "2–3 sentence executive summary synthesizing all active alerts into "
            "a single coherent incident narrative for emergency coordinators."
        ),
    )
    coordinated_strategy: list[str] = Field(
        ...,
        min_length=2,
        max_length=6,
        description=(
            "Cross-agency coordinated response strategy. Each item must specify "
            "the action, the responsible agency, and the target sector or corridor."
        ),
    )
    estimated_resolution_mins: int = Field(
        ...,
        ge=5,
        le=1440,
        description=(
            "Estimated time to full resolution in minutes, "
            "based on severity, resource availability, and historical precedent."
        ),
    )


# ─────────────────────────────────────────────────────────────────────────────
# SECTION 3 — SCHEMA EXPORT HELPERS
# These return the exact dict to pass into llama-server's response_format.
# ─────────────────────────────────────────────────────────────────────────────

def sector_alert_response_format() -> dict[str, Any]:
    """
    Returns the response_format dict for llama-server GBNF enforcement
    of SectorCascadeAlert schema.

    Usage:
        response_format = sector_alert_response_format()
        # pass directly into openai client chat.completions.create()
    """
    return {
        "type"  : "json_object",
        "schema": SectorCascadeAlert.model_json_schema(),
    }


def city_rollup_response_format() -> dict[str, Any]:
    """
    Returns the response_format dict for llama-server GBNF enforcement
    of CityCascadeRollup schema.
    """
    return {
        "type"  : "json_object",
        "schema": CityCascadeRollup.model_json_schema(),
    }


